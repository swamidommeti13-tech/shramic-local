    const reverseTranslations = new Map(
        Object.entries(translations).map(([english, telugu]) => [telugu, english])
    );
    const languageKey = "shramic_language";
    let currentLanguage = localStorage.getItem(languageKey) === "te" ? "te" : "en";

    function originalText(value) {
        return reverseTranslations.get(value) || value;
    }

    function translate(value) {
        const english = originalText(value);
        return currentLanguage === "te" ? (translations[english] || value) : english;
    }

    function applyTranslations() {
        document.documentElement.lang = currentLanguage === "te" ? "te" : "en";
        document.title = translate(document.title);
        const walker = document.createTreeWalker(document.body, NodeFilter.SHOW_TEXT);
        let node;
        while ((node = walker.nextNode())) {
            if (!node.parentElement ||
                ["SCRIPT", "STYLE"].includes(node.parentElement.tagName) ||
                node.parentElement.closest("[data-no-translate]")) continue;
            const text = node.nodeValue.trim();
            if (!text) continue;
            const translated = translate(text);
            if (translated !== text) node.nodeValue = node.nodeValue.replace(text, translated);
        }

        document.querySelectorAll("[placeholder]").forEach(element => {
            element.placeholder = translate(element.placeholder);
        });

        const languageSelect = document.getElementById("languageSelect");
        if (languageSelect) languageSelect.value = currentLanguage;
        if (typeof window.onLanguageChanged === "function") window.onLanguageChanged();
    }

    window.tr = translate;
    window.setShramicLanguage = function (language) {
        currentLanguage = language === "te" ? "te" : "en";
        localStorage.setItem(languageKey, currentLanguage);
        applyTranslations();
    };
    window.getShramicLanguage = () => currentLanguage;
    document.addEventListener("DOMContentLoaded", applyTranslations);
